"""The derivation tier is its own gate (run 2026-11-02-halt-and-order, step derivation-tier).

tests/fixtures/derivation_tier.py is the one home of every derivation the source tests hand to verify_derivation
that has 2 or more steps or a cycle: each source test imports its derivation from there, never the reverse. Each
row records exactly what its source asserts: an exact verdict, a set of allowed verdicts, or 'not HOLDS', and
the pointers it asserts. A row whose source asserts no verdict is measurement-only and never scored.

These tests score every scored row by membership through the path its source used (verify_derivation,
compose.seal_document with seal=False, audit.audit, the MCP verify tool with seal=False), and see that the path
handed verify_derivation exactly the row's listing; hold the tier's shape and its citations; prove the capture
(tests/fixtures/derivation_capture.py) sees a multi-step listing on every path; and capture every listing the
source tests pass while they run, fast and slow, and require each to be a row, excluded with its reason, or
generated by every test that passed it from a held base. The capture is in the fast suite: it does not breach the
60 s budget (checker-24 measured the suite at 34.80 s and the capture at 5.4 s), and it is the only guard on the
rows the fixture lists in reverse beside each source's own reversal. The one row from a slow source (the
1,500-step chain) is scored by the slow-marked test, in CI's slow job.
"""
from __future__ import annotations

import ast
import copy
import itertools
import json
import os
import subprocess
import sys
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"
VERDICTS = {"HOLDS", "PARTIAL", "BROKEN", "INCOMPLETE", "SCHEMA_ERROR", "SYSTEM_ERROR"}
POINTERS = {"broken_at", "gap_at", "error_at"}


def _load():
    """The fixture and the capture, imported inside each test and never at module level, so with the fixture
    absent every test here reads red rather than the file failing to collect."""
    if str(FIXTURES) not in sys.path:
        sys.path.insert(0, str(FIXTURES))
    import derivation_capture
    import derivation_tier
    return derivation_tier, derivation_capture


@pytest.fixture(scope="module", autouse=True)
def _warm():
    """Pre-pay the heavy imports outside the per-verification timeout, as the source tests do: a cold first
    statistics check can take over 8 s and be shed to ERROR."""
    from concordance import derivation as D
    D.warm()


def _agrees(spec, value):
    """Membership: an exact value, a set of allowed values ({'in': [...]}), or a value excluded ({'not': x})."""
    if isinstance(spec, dict) and "in" in spec:
        return value in spec["in"]
    if isinstance(spec, dict) and "not" in spec:
        return value != spec["not"]
    return value == spec


def _score(rows, monkeypatch, tmp_path):
    """Run every assertion of every row through its path, nothing sealed and the stores in tmp_path; return how
    many were scored and every miss: a verdict or a pointer outside what the source asserts, or a path that did
    not hand verify_derivation exactly the row's listing."""
    T, Cap = _load()
    monkeypatch.setenv("CONCORDANCE_DATA_DIR", str(tmp_path))
    for var in ("CONCORDANCE_CAS_DIR", "CONCORDANCE_LEDGER_DIR"):
        monkeypatch.delenv(var, raising=False)
    scored, misses = 0, []
    for row in rows:
        want = Cap.listing_hash(row["steps"])
        before = copy.deepcopy(row["steps"])
        for a in row["asserts"]:
            cap = Cap.Capture()
            with monkeypatch.context() as m:
                cap.install(m.setattr)
                r = T.run(row, a["path"])
            if sorted(cap.seen) != [want]:
                misses.append((row["name"], a["path"], "listing handed to verify_derivation", sorted(cap.seen)))
            if not _agrees(a["verdict"], r.get("verdict")):
                misses.append((row["name"], a["path"], "verdict", a["verdict"], r.get("verdict")))
            for field, spec in a["pointers"].items():
                if not _agrees(spec, r.get(field)):
                    misses.append((row["name"], a["path"], field, spec, r.get(field)))
            scored += 1
        assert row["steps"] == before, row["name"]          # no path changed the fixture's listing
    return scored, misses


def test_every_scored_row_holds_what_its_source_asserts(monkeypatch, tmp_path):
    T, _ = _load()
    rows = [r for r in T.rows() if r["asserts"] and not r["slow"]]
    scored, misses = _score(rows, monkeypatch, tmp_path)
    assert not misses, misses
    assert len(rows) == 39 and scored == 43, (len(rows), scored)


@pytest.mark.slow
def test_every_scored_row_from_a_slow_source_holds_what_its_source_asserts(monkeypatch, tmp_path):
    T, _ = _load()
    rows = [r for r in T.rows() if r["asserts"] and r["slow"]]
    scored, misses = _score(rows, monkeypatch, tmp_path)
    assert not misses, misses
    assert [r["name"] for r in rows] == ["chain_of(1500), listed in reverse"] and scored == 1


def _test_functions(path):
    """Every top-level test function in a source file, and whether it is marked slow."""
    tree = ast.parse((ROOT / path).read_text(encoding="utf-8"))
    out = {}
    for n in tree.body:
        if isinstance(n, ast.FunctionDef) and n.name.startswith("test_"):
            out[n.name] = any(isinstance(d, ast.Attribute) and d.attr == "slow" for d in n.decorator_list)
    return out


def test_the_tier_holds_each_derivation_once_with_what_its_source_asserts():
    """One row per listing, each in scope (2+ steps or a cycle), cited by the source tests that pass it, every
    citation a test that exists; measurement-only exactly when no source asserts a verdict; each assertion one of
    the three shapes on a known path; a row is slow exactly when every test that passes it is slow-marked; and
    every exclusion carries its reason."""
    T, Cap = _load()
    rows, excluded = T.rows(), T.EXCLUDED
    names = [r["name"] for r in rows] + [e["name"] for e in excluded]
    assert len(names) == len(set(names))
    hashes = [Cap.listing_hash(r["steps"]) for r in rows] + [Cap.listing_hash(e["steps"]) for e in excluded]
    assert len(hashes) == len(set(hashes)), "a derivation is held twice"
    funcs = {src: _test_functions(src) for src in T.SOURCES}
    for entry in rows + excluded:
        assert Cap.in_scope(entry["steps"]), entry["name"]
        assert entry["used_by"], entry["name"]
        for node in entry["used_by"]:
            src, _, fn = node.partition("::")
            assert src in funcs and fn in funcs[src], (entry["name"], node)
    for e in excluded:
        assert e["reason"].strip(), e["name"]
    for r in rows:
        assert r["measurement_only"] == (not r["asserts"]), r["name"]
        assert r["slow"] == all(funcs[n.partition("::")[0]][n.partition("::")[2]] for n in r["used_by"]), r["name"]
        for a in r["asserts"]:
            assert a["tests"] and set(a["tests"]) <= set(r["used_by"]), (r["name"], a["tests"])
            assert a["path"] in T.PATHS, (r["name"], a["path"])
            v = a["verdict"]
            allowed = v["in"] if isinstance(v, dict) and "in" in v else [v["not"]] if isinstance(v, dict) else [v]
            assert allowed and set(allowed) <= VERDICTS and (not isinstance(v, dict) or len(v) == 1), (r["name"], v)
            assert set(a["pointers"]) <= POINTERS, (r["name"], a["pointers"])
            if a["pointers"]:
                assert a["path"] in ("derivation", "mcp"), (r["name"], a["path"])   # only these return pointers
            if a["path"] in ("compose", "mcp-document"):
                assert r["doc"] and r["doc"]["steps"] == r["steps"], r["name"]
            if a["path"] == "audit":
                assert r["text"], r["name"]
    scored = [r for r in rows if r["asserts"]]
    assert (len(rows), len(scored), len(excluded)) == (63, 40, 1), (len(rows), len(scored), len(excluded))


def test_the_capture_sees_a_multi_step_listing_on_each_path(monkeypatch, tmp_path):
    """The names the capture wraps are every name verify_derivation is held by in src/, and it records a known
    multi-step listing reaching each path: direct, compose.seal_document with seal=False, the MCP verify tool
    with seal=False (given steps, and given a document), and audit.audit. A one-step listing is out of scope
    unless it is a cycle; and the permutation watch maps each generated listing to the base it came from."""
    T, Cap = _load()
    from concordance import audit as A
    from concordance import compose
    from concordance import derivation as D
    from concordance.config import EngineConfig
    from concordance.mcp.server import _call_tool
    monkeypatch.setenv("CONCORDANCE_DATA_DIR", str(tmp_path))
    rows = {r["name"]: r for r in T.rows()}
    audit_row = rows["AUDIT_TEXTS[0], as audit lists it"]
    found = sorted(str(p.relative_to(ROOT / "src")).replace("\\", "/") for p in (ROOT / "src").rglob("*.py")
                   if "import verify_derivation" in p.read_text(encoding="utf-8"))
    assert found == ["concordance/audit.py", "concordance/compose.py", "concordance/mcp/server.py",
                     "concordance/scribe/core.py"], found
    cap = Cap.Capture()
    assert cap.install(monkeypatch.setattr) == [
        "concordance.derivation.verify_derivation", "concordance.compose.verify_derivation",
        "concordance.mcp.server.verify_derivation", "concordance.scribe.core.verify_derivation"]
    C = EngineConfig()
    runs = [
        ("direct", "concordance.derivation.verify_derivation", T.ORDER_FREE["true chain"],
         lambda: D.verify_derivation(copy.deepcopy(T.ORDER_FREE["true chain"]))),
        ("compose", "concordance.compose.verify_derivation", T.COMPOSE_DOC["steps"],
         lambda: compose.seal_document(copy.deepcopy(T.COMPOSE_DOC), C, seal=False)),
        ("mcp", "concordance.mcp.server.verify_derivation", T.RECEIPT_REVERSE_CHAIN,
         lambda: _call_tool("verify", {"steps": copy.deepcopy(T.RECEIPT_REVERSE_CHAIN), "seal": False}, C)),
        ("compose", "concordance.compose.verify_derivation", T.COMPOSE_DOC["steps"],
         lambda: _call_tool("verify", {"document": copy.deepcopy(T.COMPOSE_DOC), "seal": False}, C)),
        ("audit", "concordance.derivation.verify_derivation", audit_row["steps"],
         lambda: A.audit(audit_row["text"], EngineConfig(skip_schema_validation=True), seal=False)),
    ]
    for path, name, steps, call in runs:
        cap.seen.clear()
        r = call()
        assert r.get("root") is None and r.get("seal") is None, path      # nothing sealed
        h = Cap.listing_hash(steps)
        assert list(cap.seen) == [h] and len(steps) >= 2, (path, sorted(cap.seen))
        assert cap.seen[h]["paths"] == {path} and cap.seen[h]["names"] == {name}, (path, cap.seen[h])
    # the scope: one step is in only as a cycle
    cap.seen.clear()
    D.verify_derivation([{"id": "a", "domain": "mathematics", "spec": {"mode": "numeric",
                          "params": {"numeric_expr": "2+2", "claimed_value": 4}}}])
    assert not cap.seen
    D.verify_derivation(copy.deepcopy(T.SELF_CYCLE))
    D.verify_derivation(copy.deepcopy(T.SELF_BIND))
    assert set(cap.seen) == {Cap.listing_hash(T.SELF_CYCLE), Cap.listing_hash(T.SELF_BIND)}
    # the permutation watch: each generated listing, with the base it came from and the test that generated it
    cap.watch_permutations(monkeypatch.setattr)
    base = T.ORDER_FREE["true chain"]
    me = os.environ["PYTEST_CURRENT_TEST"].rsplit(" ", 1)[0]
    perms = [list(p) for p in itertools.permutations(base)]
    assert len(perms) == 6 and perms[0] == base
    assert {Cap.listing_hash(p) for p in perms} == set(cap.sweeps)
    assert all(cap.sweeps[Cap.listing_hash(p)] == {(Cap.listing_hash(base), me)} for p in perms)
    assert list(itertools.permutations(range(3)))[1] == (0, 2, 1) and len(cap.sweeps) == 6   # non-steps: untouched
    # what the tier accounts for: held; or generated, from a held base, by EVERY test that passed it
    held, gen = Cap.listing_hash(base), Cap.listing_hash(perms[3])
    sweeps = {gen: [[held, "t.py::a"]]}
    assert Cap.unaccounted({gen: {"tests": ["t.py::a"]}}, sweeps, {held}) == []
    assert Cap.unaccounted({gen: {"tests": ["t.py::a", "t.py::b"]}}, sweeps, {held}) == [gen]   # b wrote it
    assert Cap.unaccounted({gen: {"tests": ["t.py::a"]}}, sweeps, set()) == [gen]               # base not held
    assert Cap.unaccounted({gen: {"tests": []}}, sweeps, {held}) == [gen]                       # outside any test
    assert Cap.unaccounted({held: {"tests": ["t.py::b"]}}, {}, {held}) == []                    # held


def test_every_listing_the_sources_pass_is_in_the_tier_or_excluded(tmp_path):
    """Run the source tests, fast and slow, in a process of their own with verify_derivation wrapped under every
    name and the stores in tmp_path. Every listing they pass with 2+ steps or a cycle is a row by canonical hash,
    an exclusion, or a permutation that every test passing it generated from one; every row and exclusion is
    passed by exactly the source tests it cites."""
    T, Cap = _load()
    out = tmp_path / "capture.json"
    env = {k: v for k, v in os.environ.items() if not k.startswith(("HARNESS_", "VACUITY_"))}
    for var in ("CONCORDANCE_CAS_DIR", "CONCORDANCE_LEDGER_DIR"):
        env.pop(var, None)
    env["CONCORDANCE_DATA_DIR"] = str(tmp_path / "data")
    import concordance
    src = str(Path(concordance.__file__).resolve().parent.parent)
    env["PYTHONPATH"] = os.pathsep.join([src] + [p for p in env.get("PYTHONPATH", "").split(os.pathsep) if p])
    t0 = time.monotonic()
    p = subprocess.run([sys.executable, str(FIXTURES / "derivation_capture.py"), str(out), "--", "-q",
                        "-p", "no:cacheprovider", "-m", "slow or not slow", *T.SOURCES],
                       cwd=str(ROOT), env=env, capture_output=True, text=True, timeout=600)
    took = time.monotonic() - t0
    assert p.returncode == 0, (p.stdout[-3000:], p.stderr[-3000:])
    got = json.loads(out.read_text(encoding="utf-8"))
    assert got["rc"] == 0 and got["wrapped"] == [f"{m}.{a}" for m, a in Cap.NAMES]
    held = {Cap.listing_hash(r["steps"]): r for r in T.rows()}
    held.update({Cap.listing_hash(e["steps"]): e for e in T.EXCLUDED})
    missing = [(h[:12], [s.get("id") for s in got["listings"][h]["steps"]][:8], got["listings"][h]["tests"][:3])
               for h in Cap.unaccounted(got["listings"], got["sweeps"], set(held))]
    assert not missing, missing
    for h, entry in held.items():
        assert h in got["listings"], ("no source passes", entry["name"])
        passed_by = sorted({t.split("[")[0] for t in got["listings"][h]["tests"]})
        assert passed_by == entry["used_by"], (entry["name"], passed_by)
    print(f"capture: {len(got['listings'])} listings in scope, {len(held)} held, {took:.1f} s")
